#!/usr/bin/env python3
"""
合法公開資料來源：Yahoo Finance (via yfinance)
台積電 (2330.TW) 歷史 K 線圖產生器
產生可互動的自建網頁，含時間區間、日/週/月線、MA5/10/20 勾選
"""

import yfinance as yf
import pandas as pd
import json
from datetime import datetime, timedelta
import os

def fetch_data():
    ticker = yf.Ticker("2330.TW")
    df = ticker.history(period="2y", interval="1d", auto_adjust=True)
    if df.empty:
        raise ValueError("無法取得資料，請檢查網路或代號")
    df = df.reset_index()
    df["Date"] = pd.to_datetime(df["Date"]).dt.tz_localize(None)
    df = df[["Date", "Open", "High", "Low", "Close", "Volume"]]
    df = df.dropna()
    return df

def compute_ma(df, windows=[5, 10, 20]):
    for w in windows:
        df[f"MA{w}"] = df["Close"].rolling(window=w).mean()
    return df

def resample_ohlc(df, rule):
    ohlc = df.set_index("Date").resample(rule).agg({
        "Open": "first",
        "High": "max",
        "Low": "min",
        "Close": "last",
        "Volume": "sum"
    }).dropna().reset_index()
    return compute_ma(ohlc)

def df_to_records(df):
    records = []
    for _, row in df.iterrows():
        r = {
            "date": row["Date"].strftime("%Y-%m-%d"),
            "open": round(float(row["Open"]), 2) if pd.notna(row["Open"]) else None,
            "high": round(float(row["High"]), 2) if pd.notna(row["High"]) else None,
            "low": round(float(row["Low"]), 2) if pd.notna(row["Low"]) else None,
            "close": round(float(row["Close"]), 2) if pd.notna(row["Close"]) else None,
            "volume": int(row["Volume"]) if pd.notna(row["Volume"]) else 0,
            "ma5": round(float(row["MA5"]), 2) if pd.notna(row.get("MA5")) else None,
            "ma10": round(float(row["MA10"]), 2) if pd.notna(row.get("MA10")) else None,
            "ma20": round(float(row["MA20"]), 2) if pd.notna(row.get("MA20")) else None,
        }
        records.append(r)
    return records

def filter_by_period(records, months):
    if not records:
        return []
    end_date = datetime.strptime(records[-1]["date"], "%Y-%m-%d")
    start_date = end_date - timedelta(days=months * 30 + 5)
    return [r for r in records if datetime.strptime(r["date"], "%Y-%m-%d") >= start_date]

