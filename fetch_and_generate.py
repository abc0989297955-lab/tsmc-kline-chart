def main():
    print("正在從 Yahoo Finance 抓取台積電 (2330.TW) 歷史資料...")
    df_daily = fetch_data()
    print(f"日線資料筆數: {len(df_daily)}，範圍: {df_daily['Date'].min().date()} ~ {df_daily['Date'].max().date()}")
    df_daily = compute_ma(df_daily)
    df_weekly = resample_ohlc(df_daily, "W-FRI")
    df_monthly = resample_ohlc(df_daily, "ME")
    print(f"週線筆數: {len(df_weekly)}")
    print(f"月線筆數: {len(df_monthly)}")
    daily_rec = df_to_records(df_daily)
    weekly_rec = df_to_records(df_weekly)
    monthly_rec = df_to_records(df_monthly)
